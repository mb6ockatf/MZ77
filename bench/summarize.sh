#!/bin/sh
# Print a Markdown summary of every step measured on one machine:
#   bench/summarize.sh bench/log/MACHINE > bench/log/MACHINE/SUMMARY.md
# Times are the sums of the per-file medians over the whole corpus, so the
# large files weigh most.  Speed-up = old time / new time.
set -e
dir=${1:?usage: $0 bench/log/MACHINE}
steps=$(cd "$dir" && for step in */; do
  [ -f "$step/raw/bench.csv" ] && echo "${step%/}"
done | LC_ALL=C sort)

echo "# Benchmark summary: $(basename "$dir")"
echo
echo "Generated by bench/summarize.sh from raw/bench.csv of every step."
echo "Compression and decompression times are sums of per-file medians"
echo "over the whole corpus; speed-up is old time / new time."
echo
echo "| step | ratio | compress s | decompress s | compress MB/s | decompress MB/s | compress vs previous | compress vs baseline | decompress vs previous | decompress vs baseline | archives |"
echo "|---|---|---|---|---|---|---|---|---|---|---|"
previous=
for step in $steps; do
  same=n/a
  if [ -n "$previous" ] && [ -f "$dir/$previous/raw/archives.sha256" ] \
     && [ -f "$dir/$step/raw/archives.sha256" ]; then
    if cmp -s "$dir/$previous/raw/archives.sha256" "$dir/$step/raw/archives.sha256"; then
      same="identical to previous"
    else
      same="**changed**"
    fi
  fi
  awk -F, -v step="$step" -v same="$same" 'NR > 1 {
      size += $3; arch += $4; comp += $7; dec += $8 }
    END { printf "%s %.6f %.6f %.6f %.6f %s\n", step, size, arch, comp, dec, same }' \
    "$dir/$step/raw/bench.csv"
  previous=$step
done | awk '{
    step = $1; size = $2; arch = $3; comp = $4; dec = $5
    same = $6; for (field = 7; field <= NF; field++) same = same " " $field
    if (NR == 1) { base_comp = comp; base_dec = dec; prev_comp = comp; prev_dec = dec }
    printf "| %s | %.4f | %.3f | %.3f | %.2f | %.2f | %.2fx | %.2fx | %.2fx | %.2fx | %s |\n",
      step, arch / size, comp, dec, size / 1e6 / comp, size / 1e6 / dec,
      prev_comp / comp, base_comp / comp, prev_dec / dec, base_dec / dec, same
    prev_comp = comp; prev_dec = dec
  }'

last=$(echo "$steps" | tail -1)
before=$(echo "$steps" | tail -2 | head -1)
if [ -n "$last" ] && [ "$last" != "$before" ]; then
  echo
  echo "## Per file: $last against $before"
  echo
  echo "| file | compress s before | compress s after | speed-up | decompress s before | decompress s after | speed-up |"
  echo "|---|---|---|---|---|---|---|"
  awk -F, 'FNR == 1 { file_index++; next }
    file_index == 1 { comp[$2] = $7; dec[$2] = $8; next }
    $2 in comp { printf "| %s | %.4f | %.4f | %.2fx | %.4f | %.4f | %.2fx |\n",
      $2, comp[$2], $7, comp[$2] / $7, dec[$2], $8, dec[$2] / $8 }' \
    "$dir/$before/raw/bench.csv" "$dir/$last/raw/bench.csv"
fi
